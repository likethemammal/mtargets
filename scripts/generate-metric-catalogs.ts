/**
 * Generate full MetricCatalog + MetricSuite + observation fixtures
 * from scripts/data/catalog-*.json (complete indicators, not stubs).
 *
 *   npx tsx scripts/generate-metric-catalogs.ts
 */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stringify } from "yaml";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "scripts/data");

type Ind = {
  id: string;
  title: string;
  kind: string;
  unit: string;
  higherIsWorse?: boolean;
  subjectRef?: string;
  scope?: string;
  aggregate: string;
  window?: string | Record<string, unknown>;
  source: Record<string, unknown>;
  demo: number;
  op: string;
  value: number | string | Record<string, unknown>;
  severity?: string;
  target?: number;
};

type Bundle = {
  catalogId: string;
  title: string;
  tags: string[];
  intent: string;
  subjects: Array<Record<string, unknown>>;
  indicators: Ind[];
  defaultSubjectRef?: string;
};

function toIndicator(raw: Ind, defaultSubjectRef?: string) {
  const higherIsWorse =
    raw.higherIsWorse ??
    !(raw.kind === "score" || raw.op === "gte" || raw.op === "gt");
  const out: Record<string, unknown> = {
    id: raw.id,
    title: raw.title,
    kind: raw.kind,
    unit: raw.unit,
    higherIsWorse,
    aggregate: raw.aggregate,
    window: raw.window ?? "ci",
    source: raw.source,
  };
  const subjectRef = raw.subjectRef ?? defaultSubjectRef;
  if (subjectRef) out.subjectRef = subjectRef;
  if (raw.scope) out.scope = raw.scope;
  return out;
}

function toObjective(raw: Ind) {
  const obj: Record<string, unknown> = {
    id: `${raw.id}-obj`,
    title: raw.title,
    indicator: raw.id,
    op: raw.op,
    value: raw.value,
    severity: raw.severity ?? "error",
    labels: { catalog: "full" },
  };
  if (raw.target !== undefined) obj.target = raw.target;
  return obj;
}

async function writeBundle(bundle: Bundle): Promise<void> {
  const indicators = bundle.indicators.map((i) =>
    toIndicator(i, bundle.defaultSubjectRef),
  );
  if (indicators.length < 1) throw new Error(`${bundle.catalogId} empty`);

  const catalog = {
    apiVersion: "mtargets/v1",
    kind: "MetricCatalog",
    metadata: {
      id: bundle.catalogId,
      title: bundle.title,
      version: "1.0.0",
      tags: bundle.tags,
    },
    spec: {
      subjects: bundle.subjects,
      indicators,
    },
  };

  const suite = {
    apiVersion: "mtargets/v1",
    kind: "MetricSuite",
    metadata: {
      id: bundle.catalogId,
      title: bundle.title,
      version: "1.0.0",
      tags: bundle.tags,
    },
    spec: {
      intent: bundle.intent,
      imports: [{ catalog: `../catalogs/${bundle.catalogId}.mtargets.yaml` }],
      indicators: [],
      defaults: { missing: { behavior: "fail" } },
      policy: { failOn: ["fail", "error"], warnIsFailure: false },
      objectives: bundle.indicators.map(toObjective),
    },
  };

  const observations = bundle.indicators.map((i) => ({
    indicatorId: i.id,
    observed: i.demo,
    unit: i.unit,
    ...(i.target !== undefined ? { compliance: Math.max(i.target, 0.995) } : {}),
  }));

  const catPath = path.join(
    root,
    "examples/catalogs",
    `${bundle.catalogId}.mtargets.yaml`,
  );
  const suitePath = path.join(
    root,
    "examples/suites",
    `${bundle.catalogId}.mtargets.yaml`,
  );
  const obsPath = path.join(
    root,
    "examples/observations",
    `${bundle.catalogId}-pass.json`,
  );

  await mkdir(path.dirname(catPath), { recursive: true });
  await mkdir(path.dirname(suitePath), { recursive: true });
  await mkdir(path.dirname(obsPath), { recursive: true });

  await writeFile(
    catPath,
    `# Generated by scripts/generate-metric-catalogs.ts — full indicator examples\n` +
      stringify(catalog),
    "utf8",
  );
  await writeFile(
    suitePath,
    `# Generated — imports catalog and defines an objective per indicator\n` +
      stringify(suite),
    "utf8",
  );
  await writeFile(obsPath, JSON.stringify(observations, null, 2) + "\n", "utf8");

  console.log(
    `${bundle.catalogId}: ${indicators.length} indicators → catalog + suite + observations`,
  );
}

async function main(): Promise<void> {
  const files = (await readdir(dataDir))
    .filter((f) => f.startsWith("catalog-") && f.endsWith(".json"))
    .sort();
  let total = 0;
  for (const file of files) {
    const bundle = JSON.parse(
      await readFile(path.join(dataDir, file), "utf8"),
    ) as Bundle;
    // Apply defaultSubjectRef to indicators missing subjectRef
    if (bundle.defaultSubjectRef) {
      for (const i of bundle.indicators) {
        if (!i.subjectRef) i.subjectRef = bundle.defaultSubjectRef;
      }
    }
    // Web file uses defaultSubjectRef at bundle level from extracted JSON
    const webDefault = (bundle as Bundle & { defaultSubjectRef?: string })
      .defaultSubjectRef;
    if (!webDefault && bundle.subjects.length === 1) {
      for (const i of bundle.indicators) {
        if (!i.subjectRef) i.subjectRef = String(bundle.subjects[0]!.id);
      }
    }
    await writeBundle(bundle);
    total += bundle.indicators.length;
  }
  console.log(`\nTotal indicators: ${total}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
