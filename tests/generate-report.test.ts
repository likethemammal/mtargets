import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  formatLighthousercFile,
  generateLighthousercAssertions,
  generateLighthousercConfig,
  toLhciMinScore,
} from "../src/generate-lighthouserc.js";
import { parseDocumentText } from "../src/parse.js";
import { parseProductData } from "../src/product-data.js";
import { formatAgentMarkdown } from "../src/product-report.js";
import { assertValidProductSpec } from "../src/product-schema.js";
import {
  compareProductActual,
  productValidateExitCode,
  validateProductActuals,
} from "../src/product-validate.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

function loadMinimalSpec() {
  const raw = parseDocumentText(
    readFileSync(
      path.join(root, "examples/product/v0.2-minimal.mtargets.json"),
      "utf8",
    ),
  );
  return assertValidProductSpec(raw);
}

describe("generate lighthouserc", () => {
  it("maps cwv + lighthouse-perf into LHCI assertions", () => {
    const spec = loadMinimalSpec();
    const assertions = generateLighthousercAssertions(spec);
    expect(assertions["largest-contentful-paint"]).toEqual([
      "error",
      { maxNumericValue: 2500 },
    ]);
    expect(assertions["categories:performance"]).toEqual([
      "error",
      { minScore: 0.9 },
    ]);
  });

  it("normalizes 0–100 scores to minScore 0–1", () => {
    expect(toLhciMinScore(90)).toBe(0.9);
    expect(toLhciMinScore(0.95)).toBe(0.95);
  });

  it("skips non-lighthouse product metrics", () => {
    const spec = assertValidProductSpec({
      name: "x",
      metrics: {
        "gen-fail": {
          category: "generation",
          source: "server",
          tiers: { good: 2, warn: 5 },
        },
        cls: {
          category: "cwv",
          source: "rum",
          tiers: { good: 0.1, warn: 0.25 },
        },
      },
    });
    const assertions = generateLighthousercAssertions(spec);
    expect(assertions["cumulative-layout-shift"]).toEqual([
      "error",
      { maxNumericValue: 0.1 },
    ]);
    expect(Object.keys(assertions)).toEqual(["cumulative-layout-shift"]);
  });

  it("formats cjs and json output", () => {
    const config = generateLighthousercConfig(loadMinimalSpec());
    const cjs = formatLighthousercFile(config, "cjs");
    expect(cjs).toContain("module.exports =");
    expect(cjs).toContain("Generated by mtargets generate lighthouserc");
    expect(cjs).toContain('"categories:performance"');
    expect(JSON.parse(formatLighthousercFile(config, "json"))).toEqual(config);
  });
});

describe("report --format agent-markdown", () => {
  it("classifies lower/higher-is-better tiers", () => {
    expect(
      compareProductActual(2000, { good: 2500, warn: 4000 }, "lower-is-better"),
    ).toBe("pass");
    expect(
      compareProductActual(3000, { good: 2500, warn: 4000 }, "lower-is-better"),
    ).toBe("warn");
    expect(
      compareProductActual(5000, { good: 2500, warn: 4000 }, "lower-is-better"),
    ).toBe("fail");
    expect(
      compareProductActual(92, { good: 90, warn: 75 }, "higher-is-better"),
    ).toBe("pass");
    expect(
      compareProductActual(80, { good: 90, warn: 75 }, "higher-is-better"),
    ).toBe("warn");
    expect(
      compareProductActual(60, { good: 90, warn: 75 }, "higher-is-better"),
    ).toBe("fail");
  });

  it("runs validate internally and formats route × metric markdown", () => {
    const spec = loadMinimalSpec();
    const data = parseProductData({
      dataSource: "fixture:test",
      actuals: [
        { key: "lcp", route: "/rating", actual: 1200 },
        { key: "lcp", route: "/curation/styles", actual: 3900 },
        { key: "lighthouse-perf", actual: 88 },
      ],
    });
    const report = validateProductActuals(spec, data.actuals, {
      evaluatedAt: "2026-07-11T00:00:00.000Z",
      dataSource: data.dataSource,
    });
    expect(report.summary.warn).toBeGreaterThanOrEqual(1);
    expect(report.summary.pass).toBeGreaterThanOrEqual(1);
    const rating = report.results.find(
      (r) => r.key === "lcp" && r.route === "/rating",
    );
    expect(rating?.status).toBe("pass");
    expect(rating?.delta_from_baseline).toBe(0);
    const styles = report.results.find(
      (r) => r.key === "lcp" && r.route === "/curation/styles",
    );
    expect(styles?.status).toBe("warn");
    const md = formatAgentMarkdown(report);
    expect(md).toContain("## mtargets report");
    expect(md).toContain("| Metric | Route | Status |");
    expect(md).toContain("✅ pass");
    expect(md).toContain("⚠️ warn");
    expect(md).toContain("/curation/styles");
    expect(productValidateExitCode(report.summary)).toBe(1);
  });

  it("writes generate + report artifacts", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "mtargets-cli-"));
    const outRc = path.join(dir, "lighthouserc.gen.cjs");
    const outMd = path.join(dir, "report.md");
    const spec = loadMinimalSpec();
    writeFileSync(
      outRc,
      formatLighthousercFile(generateLighthousercConfig(spec), "cjs"),
    );
    expect(readFileSync(outRc, "utf8")).toContain("categories:performance");
    const report = validateProductActuals(
      spec,
      [{ key: "lighthouse-perf", actual: 95 }],
      { dataSource: "tmp" },
    );
    writeFileSync(outMd, formatAgentMarkdown(report));
    const md = readFileSync(outMd, "utf8");
    expect(md).toContain("Lighthouse Performance Score");
    expect(md).toContain("✅ pass");
  });
});
